// Builds pages/s6-schema.js from course-content.md Appendix D (lines 4804-4888), verbatim.
// Pulls the two ```sql blocks inside that range (schema, then Lesson 13.3 sample data) and
// records their source line numbers and a sha256 so the run can prove nothing was retyped.
import fs from "node:fs";
import path from "node:path";
import crypto from "node:crypto";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const SOURCE = "/home/judah/Work/second-mind/school/cos303-hostel-paper/course/course-content.md";
const FIRST = 4804;
const LAST = 4888;

const lines = fs.readFileSync(SOURCE, "utf8").split("\n");
const blocks = [];
let open = null;
for (let n = FIRST; n <= LAST; n++) {
  const line = lines[n - 1];
  if (open === null && /^```sql\s*$/.test(line)) open = { start: n + 1, body: [] };
  else if (open !== null && /^```\s*$/.test(line)) {
    blocks.push({ startLine: open.start, endLine: n - 1, sql: open.body.join("\n") });
    open = null;
  } else if (open !== null) open.body.push(line);
}
if (blocks.length !== 2 || open !== null) throw new Error(`expected 2 sql blocks in ${FIRST}-${LAST}, found ${blocks.length}`);
if (!lines[FIRST - 1].startsWith("## D. The IHMS database schema")) throw new Error("line 4804 is not the Appendix D heading");

const [schema, sample] = blocks;
const meta = (b) => ({ startLine: b.startLine, endLine: b.endLine, sha256: crypto.createHash("sha256").update(b.sql).digest("hex") });
const out = `// AUTO-GENERATED by scripts/build-s6.mjs from course-content.md lines ${FIRST}-${LAST} (Appendix D). Do not hand-edit.
export const SCHEMA_SQL = ${JSON.stringify(schema.sql)};
export const SAMPLE_SQL = ${JSON.stringify(sample.sql)};
export const SCHEMA_SOURCE = ${JSON.stringify({ file: SOURCE, schema: meta(schema), sample: meta(sample) })};
`;
fs.writeFileSync(path.join(__dirname, "..", "pages", "s6-schema.js"), out);
console.log("wrote pages/s6-schema.js", JSON.stringify({ schema: meta(schema), sample: meta(sample) }));
